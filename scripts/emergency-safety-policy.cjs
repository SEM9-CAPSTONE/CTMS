const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const source = path.join(root, "services/api/src/modules/ai-answers/emergency-safety-policy.json");
const destination = path.join(
	root,
	"apps/mobile/lib/features/camper/data/emergency_safety_policy_data.dart"
);
const policy = JSON.parse(fs.readFileSync(source, "utf8"));
const assert = (condition, message) => {
	if (!condition) throw new Error(message);
};
const nonempty = (text) => typeof text === "string" && !!text.trim();
const lists = (value) => Array.isArray(value) && value.length > 0 && value.every(nonempty);
const phrases = (value) =>
	lists(value) && value.every((phrase) => /[a-z0-9đ]/iu.test(phrase.normalize("NFKD")));
const refs = (value) => Array.isArray(value) && value.every(nonempty);
const validStatus = (value) => ["PENDING", "APPROVED"].includes(value);
const datedReview = ({ reviewer, approvedAt }) =>
	nonempty(reviewer) && nonempty(approvedAt) && Number.isFinite(Date.parse(approvedAt));

assert(
	nonempty(policy.version) && JSON.stringify(policy.languages) === '["vi","en"]',
	"Invalid safety policy identity or languages"
);
assert(
	validStatus(policy.review.status) && refs(policy.review.sourceReferences),
	"Invalid assessment governance"
);
assert(
	validStatus(policy.outputReview.status) && refs(policy.outputReview.sourceReferences),
	"Invalid output safety governance"
);
const patternKeys = [
	"clauseBreak",
	"prevention",
	"knowledge",
	"hypothetical",
	"past",
	"current",
	"self",
	"other",
	"negation",
	"postNegation",
	"resolution",
	"possibleIncident",
	"rescue",
	"unsupportedOutput",
];
assert(
	patternKeys.every((key) => phrases(policy.patterns[key])),
	"Missing or invalid patterns"
);
const signalIds = new Set();
for (const item of policy.signals) {
	assert(nonempty(item.id) && !signalIds.has(item.id), "Missing or duplicate signal ID");
	assert(["WARNING", "EMERGENCY"].includes(item.level), "Unsupported signal severity");
	assert(
		typeof item.implicit === "boolean" && phrases(item.expressions),
		"Invalid signal expressions"
	);
	signalIds.add(item.id);
}
assert(signalIds.size > 0, "Missing safety signals");
const protocols = new Map();
for (const item of policy.protocols) {
	assert(nonempty(item.id) && !protocols.has(item.id), "Missing or duplicate protocol ID");
	assert(Number.isSafeInteger(item.version) && item.version > 0, "Invalid content version");
	assert(
		Array.isArray(item.signalIds) && item.signalIds.every((id) => signalIds.has(id)),
		"Invalid protocol signal ID"
	);
	assert(
		validStatus(item.reviewStatus) && refs(item.sourceReferences),
		"Invalid protocol review metadata"
	);
	assert(
		item.locales && typeof item.locales === "object" && !Array.isArray(item.locales),
		"Invalid protocol locales"
	);
	for (const [lang, copy] of Object.entries(item.locales)) {
		assert(
			policy.languages.includes(lang) &&
				nonempty(copy.title) &&
				lists(copy.guidance) &&
				refs(copy.warnings),
			"Invalid localized protocol text"
		);
	}
	if (item.reviewStatus === "APPROVED") {
		assert(
			lists(item.sourceReferences) && policy.languages.every((lang) => item.locales[lang]),
			"Approved protocol lacks provenance or localized content"
		);
	}
	protocols.set(item.id, item);
}
const mandatoryIds = ["WARNING", "EMERGENCY", "fallback"].map((key) => policy.routes[key]);
assert(
	mandatoryIds.every((id) => protocols.has(id)),
	"Missing mandatory protocol reference"
);
assert(
	policy.signals.every((item) =>
		protocols.get(policy.routes[item.level]).signalIds.includes(item.id)
	),
	"A signal has no applicable protocol"
);
for (const key of ["incident_timing", "incident_details"]) {
	assert(
		policy.languages.every((lang) => nonempty(policy.clarifications[key][lang])),
		"Missing clarification"
	);
}
const releaseApproved =
	policy.review.status === "APPROVED" &&
	datedReview(policy.review) &&
	lists(policy.review.sourceReferences) &&
	nonempty(policy.review.evaluationReference) &&
	policy.outputReview.status === "APPROVED" &&
	lists(policy.outputReview.sourceReferences) &&
	mandatoryIds.every((id) => protocols.get(id).reviewStatus === "APPROVED");

if (process.argv.includes("--release"))
	assert(
		releaseApproved,
		"CTMS-075 release blocked: reviewed policy, evaluation, and approved mandatory content required"
	);

// Dart uses the same compatibility decomposition table as the matching rules.
const unicode = {};
for (const [from, through] of [
	[0x00a0, 0x024f],
	[0x1e00, 0x1eff],
	[0x2000, 0x206f],
	[0xfb00, 0xfb06],
	[0xff00, 0xffef],
]) {
	for (let cp = from; cp <= through; cp++) {
		const char = String.fromCodePoint(cp);
		const normalized = char.toLowerCase().normalize("NFKD");
		if (normalized !== char) unicode[char] = normalized;
	}
}
const dart = [
	"// Generated by scripts/emergency-safety-policy.cjs. Edit the canonical JSON instead.",
	`const emergencySafetyReleaseApproved = ${releaseApproved};`,
	"const emergencySafetyPolicyJson = r" + "'''",
	JSON.stringify(policy, null, 2),
	"''';",
	"const emergencySafetyUnicodeJson = r" + "'''",
	JSON.stringify(unicode),
	"''';",
	"",
].join("\n");
if (process.argv.includes("--write")) fs.writeFileSync(destination, dart);
else
	assert(
		fs.readFileSync(destination, "utf8").replace(/\r\n/g, "\n") === dart,
		"Mobile policy bundle is stale. Run with --write."
	);
console.log(
	policy.version + (releaseApproved ? " (content approved)" : " (engineering preview only)")
);
